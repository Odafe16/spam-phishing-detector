from pathlib import Path
import sys

# I make the project root available for local imports.
PROJECT_ROOT = Path(__file__).resolve().parent.parent

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import streamlit as st
from src.inference import predict_sms, predict_email, predict_url


st.set_page_config(
    page_title="Spam & Phishing Detector",
    page_icon="🛡️",
    layout="wide",
    initial_sidebar_state="collapsed",
)


# I define a minimal application theme.
st.markdown(
    """
    <style>
    .block-container {
        max-width: 1100px;
        padding-top: 2.5rem;
        padding-bottom: 3rem;
    }

    h1, h2, h3 {
        color: #1F2937;
    }

    .app-subtitle {
        color: #64748B;
        font-size: 1.05rem;
        margin-top: -0.5rem;
        margin-bottom: 1.5rem;
    }

    .app-footer {
        color: #64748B;
        font-size: 0.85rem;
        margin-top: 3rem;
        padding-top: 1rem;
        border-top: 1px solid #E5E7EB;
    }
    </style>
    """,
    unsafe_allow_html=True,
)


# I display the application introduction.
st.title("🛡️ Spam & Phishing Detector")

st.markdown(
    """
    <div class="app-subtitle">
        Machine learning tools for analyzing suspicious messages,
        emails, and URLs.
    </div>
    """,
    unsafe_allow_html=True,
)


# I organize the three detection tools into separate tabs.
sms_tab, email_tab, url_tab = st.tabs(
    [
        "💬 SMS Detection",
        "✉️ Email Detection",
        "🔗 URL Detection",
    ]
)


with sms_tab:
    st.subheader("SMS Spam Detection")

    st.write(
        "Paste a text message below to check for patterns "
        "associated with spam."
    )

    with st.form("sms_detection_form"):
        sms_input = st.text_area(
            "Message",
            placeholder=(
                "Enter or paste an SMS message here..."
            ),
            height=160,
            max_chars=100_000,
        )

        sms_submit = st.form_submit_button(
            "Analyze Message",
            type="primary",
            use_container_width=True,
        )

    if sms_submit:
        if not sms_input.strip():
            st.warning("Please enter an SMS message to analyze.")

        else:
            try:
                with st.spinner("Analyzing message..."):
                    sms_result = predict_sms(sms_input)

                if sms_result["prediction"] == 1:
                    st.error(
                        "Potential Spam Detected",
                        icon="⚠️",
                    )
                else:
                    st.success(
                        "No Spam Detected",
                        icon="✅",
                    )

                st.write(sms_result["message"])

                st.caption(
                    "This classification is generated by a "
                    "machine-learning model and is not a "
                    "guarantee of message legitimacy."
                )

            except (ValueError, TypeError) as exc:
                st.warning(str(exc))

            except Exception:
                st.error(
                    "The message could not be analyzed. "
                    "Please try again."
                )


with email_tab:
    st.subheader("Email Phishing Detection")

    st.write(
        "Paste an email below to identify patterns "
        "associated with phishing."
    )

    with st.form("email_detection_form"):
        email_input = st.text_area(
            "Email Content",
            placeholder=(
                "Paste the email subject and message body here..."
            ),
            height=220,
            max_chars=100_000,
        )

        email_submit = st.form_submit_button(
            "Analyze Email",
            type="primary",
            use_container_width=True,
        )

    if email_submit:
        if not email_input.strip():
            st.warning(
                "Please enter email content to analyze."
            )

        else:
            try:
                with st.spinner("Analyzing email..."):
                    email_result = predict_email(email_input)

                if email_result["prediction"] == 1:
                    st.error(
                        "Potential Phishing Detected",
                        icon="⚠️",
                    )
                else:
                    st.success(
                        "No Phishing Detected",
                        icon="✅",
                    )

                st.write(email_result["message"])

                st.caption(
                    "This classifier analyzes the supplied text "
                    "only. It does not inspect attachments, "
                    "verify senders, or check linked websites. "
                    "A negative prediction does not guarantee "
                    "that an email is safe."
                )

            except (ValueError, TypeError) as exc:
                st.warning(str(exc))

            except Exception:
                st.error(
                    "The email could not be analyzed. "
                    "Please try again."
                )


with url_tab:
    st.subheader("URL Phishing Detection")

    st.write(
        "Analyze a URL for structural patterns associated "
        "with phishing attempts."
    )

    st.caption(
        "The model examines the URL string only. "
        "It does not open the link or inspect website content."
    )

    with st.form("url_detection_form"):
        url_input = st.text_input(
            "Website URL",
            placeholder="https://example.com",
            max_chars=4096,
        )

        url_submit = st.form_submit_button(
            "Analyze URL",
            type="primary",
            use_container_width=True,
        )

    if url_submit:
        if not url_input.strip():
            st.warning("Please enter a URL to analyze.")

        else:
            try:
                with st.spinner("Analyzing URL structure..."):
                    url_result = predict_url(url_input)

                phishing_score = url_result["phishing_probability"]
                threshold = url_result["threshold"]

                if url_result["prediction"] == 1:
                    st.error(
                        "Potential Phishing URL",
                        icon="⚠️",
                    )
                    st.write(
                        "The model identified URL characteristics "
                        "associated with phishing examples."
                    )

                else:
                    st.info(
                        "No Phishing Indicators Flagged",
                        icon="ℹ️",
                    )
                    st.write(
                        "The model did not flag this URL. "
                        "This does not establish that the "
                        "destination is safe."
                    )

                st.markdown("#### Model Analysis")

                col1, col2 = st.columns(2)

                with col1:
                    st.metric(
                        "Model phishing score",
                        f"{phishing_score:.1%}",
                    )

                with col2:
                    st.metric(
                        "Classification threshold",
                        f"{threshold:.0%}",
                    )

                st.progress(
                    min(max(phishing_score, 0.0), 1.0)
                )

                st.caption(
                    "The phishing score is an uncalibrated "
                    "model estimate, not a verified probability "
                    "that the website is malicious."
                )

                st.warning(
                    "Research limitation: This classifier "
                    "performed poorly on several unfamiliar "
                    "hosting platforms during evaluation. "
                    "In particular, it missed many phishing "
                    "examples hosted on Google Docs and "
                    "Google Sites. Never treat a negative "
                    "prediction as proof of safety."
                )

            except (ValueError, TypeError) as exc:
                st.warning(str(exc))

            except Exception:
                st.error(
                    "The URL could not be analyzed. "
                    "Please check your input and try again."
                )


